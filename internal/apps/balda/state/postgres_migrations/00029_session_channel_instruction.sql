-- +goose Up
-- Repair only the generated channel/session header using canonical locator data.
-- Keep ACP identity, capabilities, history and all later instructions unchanged.
WITH bound_instructions AS (
    SELECT runtime.app_name, runtime.user_id, runtime.session_id,
           runtime.state_json::jsonb #>> '{acp_session,meta,codex,developerInstructions}' AS instruction,
           'Context:
- You are communicating with the Balda bot owner or an authorized collaborator.
- This session belongs to channel type: telegram.

Session:
- ID: ' || runtime.session_id || '
- Session IDs are channel-scoped internal identifiers generated by balda.
- Telegram sessions use IDs like `tg-<chat_id>-<topic_id>`.
' AS previous_context,
           'Context:
- You are communicating with the Balda bot owner or an authorized collaborator.
- This session belongs to channel type: ' || metadata.channel_type || '.

Session:
- ID: ' || runtime.session_id || '
- Session IDs are channel-scoped internal identifiers generated by balda.
' AS current_context
    FROM balda_runtime_sessions AS runtime
    JOIN balda_session_metadata AS metadata ON metadata.session_id = runtime.session_id
    WHERE metadata.channel_type <> 'telegram' AND trim(metadata.channel_type) <> ''
), positioned AS (
    SELECT *, strpos(instruction, previous_context) AS context_at
    FROM bound_instructions
), repaired AS (
    SELECT app_name, user_id, session_id,
           substr(instruction, 1, context_at - 1) || current_context ||
           substr(instruction, context_at + length(previous_context)) AS instruction
    FROM positioned
    WHERE context_at > 0 AND context_at < strpos(instruction, '
Workspace settings:
')
      AND substr(instruction, 1, 72 + 1) = 'You are Balda, an AI assistant operating inside a Balda channel session.
'
)
UPDATE balda_runtime_sessions AS runtime
SET state_json = jsonb_set(runtime.state_json::jsonb, '{acp_session,meta,codex,developerInstructions}', to_jsonb(repaired.instruction), false)::text
FROM repaired
WHERE runtime.app_name = repaired.app_name AND runtime.user_id = repaired.user_id
  AND runtime.session_id = repaired.session_id;

