func up00064SessionChannelInstruction(ctx context.Context, tx *sql.Tx) error {
	// Older databases may have placeholder runtime tables without persisted ACP
	// state. They contain no generated instructions to repair; keep them intact.
	for _, column := range []string{"app_name", "user_id", "session_id", "state_json"} {
		exists, err := sqliteTxTableHasColumn(ctx, tx, "balda_runtime_sessions", column)
		if err != nil {
			return fmt.Errorf("inspect runtime session column %s: %w", column, err)
		}
		if !exists {
			return nil
		}
	}

	// Repair only the generated header using the canonical channel binding.
	// Preserve ACP identity, capabilities, history and all later instructions.
	if _, err := tx.ExecContext(ctx, `
WITH bound_instructions AS (
    SELECT runtime.app_name, runtime.user_id, runtime.session_id,
           json_extract(runtime.state_json, '$.acp_session.meta.codex.developerInstructions') AS instruction,
           'Context:
- You are communicating with the Balda bot owner or an authorized collaborator.
- This session belongs to channel type: telegram.

Session:
- ID: ' || runtime.session_id || '
- Session IDs are channel-scoped internal identifiers generated by balda.
- Telegram sessions use IDs like ' || char(96) || 'tg-<chat_id>-<topic_id>' || char(96) || '.
' AS previous_context,
           'Context:
- You are communicating with the Balda bot owner or an authorized collaborator.
- This session belongs to channel type: ' || metadata.channel_type || '.

Session:
- ID: ' || runtime.session_id || '
- Session IDs are channel-scoped internal identifiers generated by balda.
' AS current_context
    FROM balda_runtime_sessions AS runtime
    JOIN balda_session_metadata AS metadata ON metadata.session_id = runtime.session_id
    WHERE metadata.channel_type <> 'telegram' AND trim(metadata.channel_type) <> ''
), positioned AS (
    SELECT app_name, user_id, session_id, instruction, previous_context, current_context,
           instr(instruction, previous_context) AS context_at
    FROM bound_instructions
), repaired AS (
    SELECT app_name, user_id, session_id,
           substr(instruction, 1, context_at - 1) || current_context ||
           substr(instruction, context_at + length(previous_context)) AS instruction
    FROM positioned
    WHERE context_at > 0 AND context_at < instr(instruction, '
Workspace settings:
')
      AND substr(instruction, 1, 72 + 1) = 'You are Balda, an AI assistant operating inside a Balda channel session.
'
)
UPDATE balda_runtime_sessions AS runtime
SET state_json = json_set(runtime.state_json, '$.acp_session.meta.codex.developerInstructions', repaired.instruction)
FROM repaired
WHERE runtime.app_name = repaired.app_name AND runtime.user_id = repaired.user_id
  AND runtime.session_id = repaired.session_id;
`); err != nil {
		return fmt.Errorf("repair session channel instructions: %w", err)
	}
	return nil
}

