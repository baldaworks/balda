func TestSQLiteSessionChannelInstructionUpgradePreservesRuntimeState(t *testing.T) {
	db, err := sql.Open("sqlite", sqliteConnectionString(filepath.Join(t.TempDir(), "state.db")))
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = db.Close() }()
	registerBaldaGoMigrations()
	migrations, err := fs.Sub(baldaMigrationsFS, "migrations")
	if err != nil {
		t.Fatal(err)
	}
	p, err := goose.NewProvider(goose.DialectSQLite3, db, migrations)
	if err != nil {
		t.Fatal(err)
	}
	checkSessionChannelInstructionUpgrade(t, db, p, 63, func(q string) string { return q })
}

func TestSQLiteSessionChannelInstructionUpgradePreservesIncompleteRuntimeSchemas(t *testing.T) {
	for _, missing := range []string{"app_name", "user_id", "session_id", "state_json"} {
		t.Run("without_"+missing, func(t *testing.T) {
			db, err := sql.Open("sqlite", sqliteConnectionString(filepath.Join(t.TempDir(), "state.db")))
			if err != nil {
				t.Fatal(err)
			}
			defer func() { _ = db.Close() }()
			registerBaldaGoMigrations()
			migrations, err := fs.Sub(baldaMigrationsFS, "migrations")
			if err != nil {
				t.Fatal(err)
			}
			p, err := goose.NewProvider(goose.DialectSQLite3, db, migrations)
			if err != nil {
				t.Fatal(err)
			}
			if _, err := p.UpTo(t.Context(), 63); err != nil {
				t.Fatal(err)
			}
			if _, err := db.ExecContext(t.Context(), `DROP TABLE balda_runtime_sessions`); err != nil {
				t.Fatal(err)
			}
			columns := []string{"id INTEGER PRIMARY KEY"}
			for _, column := range []string{"app_name", "user_id", "session_id", "state_json"} {
				if column != missing {
					columns = append(columns, column+" TEXT")
				}
			}
			schema := "CREATE TABLE balda_runtime_sessions (" + strings.Join(columns, ", ") + ")"
			if _, err := db.ExecContext(t.Context(), schema); err != nil {
				t.Fatal(err)
			}
			if _, err := db.ExecContext(t.Context(), `INSERT INTO balda_runtime_sessions(id) VALUES (42)`); err != nil {
				t.Fatal(err)
			}
			if _, err := p.Up(t.Context()); err != nil {
				t.Fatalf("upgrade incomplete runtime schema: %v", err)
			}
			var id int
			if err := db.QueryRowContext(t.Context(), `SELECT id FROM balda_runtime_sessions`).Scan(&id); err != nil {
				t.Fatal(err)
			}
			if id != 42 {
				t.Fatalf("runtime placeholder id = %d, want 42", id)
			}
			var gotSchema string
			if err := db.QueryRowContext(t.Context(), `SELECT sql FROM sqlite_master WHERE name = 'balda_runtime_sessions'`).Scan(&gotSchema); err != nil {
				t.Fatal(err)
			}
			if gotSchema != schema {
				t.Fatalf("runtime schema changed: %q, want %q", gotSchema, schema)
			}
			if applied, err := p.Up(t.Context()); err != nil || len(applied) != 0 {
				t.Fatalf("reopen upgraded database = %v, %v; want no migrations", applied, err)
			}
		})
	}
}

func checkSessionChannelInstructionUpgrade(t *testing.T, db *sql.DB, p *goose.Provider, previous int64, bind func(string) string) {
	t.Helper()
	if _, err := p.UpTo(t.Context(), previous); err != nil {
		t.Fatal(err)
	}
	header := "You are Balda, an AI assistant operating inside a Balda channel session.\n\n"
	contextPrefix := "Context:\n- You are communicating with the Balda bot owner or an authorized collaborator.\n- This session belongs to channel type: "
	contextTail := "\n- Session IDs are channel-scoped internal identifiers generated by balda.\n"
	telegramHint := "- Telegram sessions use IDs like `tg-<chat_id>-<topic_id>`.\n"
	type testCase struct {
		id, channel, instruction, want string
		missingACP                     bool
	}
	var cases []testCase
	for _, channel := range []string{"mattermost", "slack", "telegram", ""} {
		id := "session-" + channel
		oldContext := contextPrefix + "telegram.\n\nSession:\n- ID: " + id + contextTail + telegramHint
		suffix := "\nWorkspace settings:\n- Path: /workspace\n\nGlobal instruction:\nPreserve this user text and an example: " + oldContext
		instruction := header + oldContext + suffix
		want := instruction
		if channel != "" && channel != "telegram" {
			want = header + contextPrefix + channel + ".\n\nSession:\n- ID: " + id + contextTail + suffix
		}
		cases = append(cases, testCase{id: id, channel: channel, instruction: instruction, want: want})
	}
	correctID := "session-correct"
	correct := header + contextPrefix + "mattermost.\n\nSession:\n- ID: " + correctID + contextTail + "\nWorkspace settings:\n- Path: /workspace\n"
	cases = append(cases, testCase{id: correctID, channel: "mattermost", instruction: correct, want: correct}, testCase{id: "session-custom", channel: "mattermost", instruction: "User-owned instructions: channel type telegram in a quoted example", want: "User-owned instructions: channel type telegram in a quoted example"}, testCase{id: "session-without-acp", channel: "mattermost", missingACP: true})
	expected := make(map[string]map[string]any)
	for _, tc := range cases {
		state := map[string]any{"balda_session_id": tc.id, "cwd": "/workspace", "memory": "keep", "other": map[string]any{"number": float64(7)}}
		if !tc.missingACP {
			state["acp_session"] = map[string]any{"session_id": "provider-" + tc.id, "meta": map[string]any{"codex": map[string]any{"developerInstructions": tc.instruction, "config": map[string]any{"model_reasoning_effort": "medium"}}, "other": "preserve"}}
		}
		data, err := json.Marshal(state)
		if err != nil {
			t.Fatal(err)
		}
		if _, err := db.ExecContext(t.Context(), bind(`INSERT INTO balda_runtime_sessions(app_name,user_id,session_id,state_json,updated_at) VALUES ('norma-balda','owner',?,?,'2026-10-15T00:00:00Z')`), tc.id, string(data)); err != nil {
			t.Fatal(err)
		}
		if _, err := db.ExecContext(t.Context(), bind(`INSERT INTO balda_session_metadata(session_id,agent_name,workspace_dir,branch_name,status,updated_at,channel_type,address_key,user_id,runtime_snapshot_id) VALUES (?,'codex','/workspace','n/a','active','2026-10-15T00:00:00Z',?,?,'owner','snapshot-proof')`), tc.id, tc.channel, "exact-address-"+tc.id); err != nil {
			t.Fatal(err)
		}
		if _, err := db.ExecContext(t.Context(), bind(`INSERT INTO balda_runtime_events(app_name,user_id,session_id,event_id,ordinal,timestamp,event_json) VALUES ('norma-balda','owner',?,'event-1',1,'2026-10-15T00:00:00Z','{"content":"preserved"}')`), tc.id); err != nil {
			t.Fatal(err)
		}
		if !tc.missingACP {
			state["acp_session"].(map[string]any)["meta"].(map[string]any)["codex"].(map[string]any)["developerInstructions"] = tc.want
		}
		expected[tc.id] = state
	}
	if _, err := p.Up(t.Context()); err != nil {
		t.Fatal(err)
	}
	for _, tc := range cases {
		var data, event, address, snapshot, status string
		if err := db.QueryRowContext(t.Context(), bind(`SELECT state_json FROM balda_runtime_sessions WHERE session_id=?`), tc.id).Scan(&data); err != nil {
			t.Fatal(err)
		}
		var got map[string]any
		if err := json.Unmarshal([]byte(data), &got); err != nil {
			t.Fatal(err)
		}
		if !reflect.DeepEqual(got, expected[tc.id]) {
			t.Errorf("session %q state = %#v, want %#v", tc.id, got, expected[tc.id])
		}
		if err := db.QueryRowContext(t.Context(), bind(`SELECT event_json FROM balda_runtime_events WHERE session_id=?`), tc.id).Scan(&event); err != nil {
			t.Fatal(err)
		}
		if event != `{"content":"preserved"}` {
			t.Errorf("session %q event = %q", tc.id, event)
		}
		if err := db.QueryRowContext(t.Context(), bind(`SELECT address_key,runtime_snapshot_id,status FROM balda_session_metadata WHERE session_id=?`), tc.id).Scan(&address, &snapshot, &status); err != nil {
			t.Fatal(err)
		}
		if address != "exact-address-"+tc.id || snapshot != "snapshot-proof" || status != "active" {
			t.Errorf("session %q metadata changed: %q %q %q", tc.id, address, snapshot, status)
		}
		if !tc.missingACP && !strings.Contains(data, "provider-"+tc.id) {
			t.Errorf("session %q lost provider identity", tc.id)
		}
	}
}
